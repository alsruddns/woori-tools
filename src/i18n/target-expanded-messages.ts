export function getTargetExpandedMessages(locale: ExpandedTargetLocale): Record<ExpandedMessageKey, string> {
  const translated = translatedMessages[locale];
  const result = { ...translated } as Record<ExpandedMessageKey, string>;
  for (const [expandedKey, coreKey] of Object.entries(coreKeyByExpandedKey) as [ExpandedMessageKey, TargetCoreMessageKey][]) {
    result[expandedKey] = targetCoreMessages[locale][coreKey];
  }
  Object.assign(result, reviewedCorrections[locale]);
  return result;
}

export const targetExpandedMessageLocales = Object.keys(translatedMessages) as ExpandedTargetLocale[];
const targetExpandedLocaleSet: ReadonlySet<string> = new Set(targetExpandedMessageLocales);

export function isExpandedTargetLocale(locale: import("./routing").TargetLocale): locale is ExpandedTargetLocale {
  return targetExpandedLocaleSet.has(locale);
}
