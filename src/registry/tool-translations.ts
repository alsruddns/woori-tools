export function localizeTool<T extends ToolDefinition>(tool: T, locale: Locale): T {
  if (locale === "ko") return tool;
  const [title, description] = catalogs[locale][tool.slug] ?? [];
  if (!title || !description) throw new Error(`Missing ${locale} translation for ${tool.slug}`);
  const languageKeywords = locale === "en"
    ? ["free online tool", "browser tool"]
    : locale === "ja"
      ? ["無料オンラインツール", "ブラウザツール"]
      : ["免费在线工具", "浏览器工具"];
  return { ...tool, title, shortTitle: title, description, keywords: [tool.slug, title, ...languageKeywords] };
}

export function localizeTools<T extends ToolDefinition>(tools: T[], locale: Locale): T[] {
  return tools.map((tool) => localizeTool(tool, locale));
}
